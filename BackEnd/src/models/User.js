const mongoose = require('mongoose');

const userSchema = new mongoose.Schema(
  {
    name: {
      type: String,
      required: true,
      trim: true,
      maxlength: 100
    },

    email: {
      type: String,
      required: true,
      unique: true,
      lowercase: true,
      trim: true
    },

    password: {
      type: String,
      required: true,
      minlength: 6,
      select: false
    },

    role: {
      type: String,
      enum: ['Admin', 'Editor', 'Author', 'Reader'],
      default: 'Reader'
    }
  },
  {
    timestamps: true
  }
);

module.exports = mongoose.model('User', userSchema);